export function t(key: string, language: Language, vars: Record<string, string | number> = {}): string {
  const text = dictionary[language]?.[key] ?? dictionary.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (match, name: string) => vars[name] === undefined ? match : String(vars[name]));
}

/** First visit follows a supported browser language, otherwise Portuguese. */
export function detectLanguage(): Language {
  if (typeof navigator === 'undefined') return 'pt';
  for (const locale of navigator.languages?.length ? navigator.languages : [navigator.language]) {
    const language = locale?.toLowerCase().split('-')[0];
    if (language === 'pt' || language === 'fr' || language === 'en') return language;
  }
  return 'pt';
}
